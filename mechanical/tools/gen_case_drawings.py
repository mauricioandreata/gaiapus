#!/usr/bin/env python3
"""Gaiapus head case rev B: 3 A3 sheets (PDF), all views as DXF, and the clearance report.
Run from anywhere:  python3 mechanical/tools/gen_case_drawings.py      (needs matplotlib)
Dimensions live in params.py; checks in checks.py.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
OUT = os.path.normpath(os.path.join(HERE, "..", "drawings")); os.makedirs(OUT, exist_ok=True)
from matplotlib.backends.backend_pdf import PdfPages
import sheet_overview, sheet_base, sheet_lid, checks
from drawlib import write_dxf, DXF_LAYER

sheets = [m.build(3) for m in (sheet_overview, sheet_base, sheet_lid)]
pdf = os.path.join(OUT, "gaiapus-case-revB.pdf")
with PdfPages(pdf) as p:
    d = p.infodict(); d["Title"] = "Gaiapus head case - rev B"; d["Author"] = "Team Gaiapus - Mechanical"
    for s in sheets: s.render(p)
print("wrote", pdf)

groups, col, row = [], 0, 0
for s in sheets:
    for v in s.views:
        us = [q[0] for e in v.ents if e[0] == "poly" for q in e[1]]; vs = [q[1] for e in v.ents if e[0] == "poly" for q in e[1]]
        if not us: continue
        dx, dy = col * 200 - min(us), -row * 160 - max(vs)
        ents = [("poly", [(a + dx, b + dy) for a, b in e[1]], DXF_LAYER[e[2]]) for e in v.ents if e[0] == "poly" and e[2] != "dim"]
        ents.append(("text", (min(us) + dx, max(vs) + dy + 8), "%s (sheet %d)" % (v.name, s.num), 5.0))
        groups.append((v.name, ents)); col += 1
        if col == 3: col, row = 0, row + 1
dxf = os.path.join(OUT, "gaiapus-case-revB-views.dxf"); write_dxf(dxf, groups); print("wrote", dxf)

rep = os.path.join(OUT, "clearance-report-revB.md")
with open(rep, "w", encoding="utf-8") as f:
    f.write("# Clearance checks, case rev B\n\nGenerated by `tools/checks.py` from `tools/params.py`.\n\n| Check | Value (mm) | Min | Result | Note |\n|---|---|---|---|---|\n")
    for n, val, mn, ok, note in checks.rows():
        f.write("| %s | %.2f | %.1f | %s | %s |\n" % (n, val, mn, "OK" if ok else "**FAIL**", note))
print("wrote", rep)
